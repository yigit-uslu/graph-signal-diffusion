    # Metadata helpers
    # ------------------------------------------------------------------

    @staticmethod
    def _replicate_metadata(
        metadata: Dict[str, Any], n: int
    ) -> Dict[str, Any]:
        """Replicate tensor-valued metadata entries ``n`` times along dim 0.

        Tensors that encode per-stock data in PyG-batched layout
        ``[B*N, ...]`` (such as ``close_price`` and ``close_price_y``)
        need batch-aware replication: reshape to ``[B, N, ...]``,
        replicate along dim 0 to ``[B*n, N, ...]``, then flatten back
        to ``[B*n*N, ...]``.  Naive ``repeat_interleave`` on the flat
        tensor would garble the stock ordering.
        """
        N = metadata.get('num_stocks', None)
        B = metadata.get('batch_size', None)
        # Keys that have [B*N, ...] layout in PyG-batched data
        per_stock_keys = {'close_price', 'close_price_y', 'stocks_index'}

        out: Dict[str, Any] = {}
        for key, val in metadata.items():
            if not isinstance(val, torch.Tensor) or val.dim() < 1:
                out[key] = val
                continue

            if key in per_stock_keys and N is not None and B is not None:
                total = val.shape[0]
                expected_flat = B * N
                if total == expected_flat:
                    # Reshape [B*N, ...] -> [B, N, ...], replicate along
                    # batch dim, then flatten back to [B*n*N, ...]
                    rest = val.shape[1:]  # remaining dims
                    val_bn = val.view(B, N, *rest)              # [B, N, ...]
                    val_bn = val_bn.repeat_interleave(n, dim=0)  # [B*n, N, ...]
                    out[key] = val_bn.reshape(B * n * N, *rest)  # [B*n*N, ...]
                    continue

            # Default: simple repeat_interleave on dim 0
            out[key] = val.repeat_interleave(n, dim=0)
        return out

