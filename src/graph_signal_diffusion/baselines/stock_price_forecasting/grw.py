@BASELINE_REGISTRY.register("grw")
class GeometricRandomWalk(BaseBaseline):
    """
    Static Geometric Random Walk baseline for stock price forecasting.

    Fits per-stock i.i.d. Gaussian log-return parameters once on the training
    set using empirical Bayes shrinkage, then generates unconditional samples
    at test time (ignoring the historical window).

    The baseline operates entirely in **standardized** space (z-scored log
    returns with std ≈ 1).  TaskV2's destandardisation pipeline converts both
    generated and real samples back to raw log returns and prices for metric
    computation.

    Attributes:
        has_ensemble_evaluate: Signals to ``UnifiedEvaluator`` that this
            baseline handles its own multi-sample evaluation via ``evaluate()``.
    """

    # Let the evaluator know we handle ensemble evaluation ourselves.
    has_ensemble_evaluate: bool = True

    def __init__(
        self,
        device: str = "cuda",
        n_samples: int = 20,
        shrinkage_strength: float = 10.0,
        min_samples_per_stock: int = 20,
        evaluation: Optional[Dict[str, Any]] = None,
        **kwargs,
    ):
        """
        Args:
            device: Device to run computations on.
            n_samples: Number of Monte-Carlo samples per input for ensemble
                evaluation.
            shrinkage_strength: Bayesian shrinkage hyper-parameter *k*.
                Effective shrinkage weight per stock is λ = n_s / (n_s + k).
            min_samples_per_stock: Minimum observations required to estimate
                per-stock parameters; stocks with fewer observations fall back
                to global estimates.
            evaluation: Nested dict of evaluation-time settings.  When
                instantiated via Hydra the ``evaluation:`` YAML sub-tree is
                automatically passed as a dict.  Recognised keys:

                - *structural_metrics* (``bool``, default ``False``): compute
                  autocorrelation-of-r² and eigenvalue-spectrum diagnostics.
                - *structural_max_lag* (``int``, default ``2``): max lag for
                  the autocorrelation profile.
                - *structural_n_eigenvalues* (``int``, default ``5``): number
                  of top eigenvalues to compute.
                - *nll_metrics* (``bool``, default ``False``): compute
                  per-trajectory NLL under the fitted GRW and Wasserstein-1.
                - *log_every_n_batches* (``int``, default ``10``): progress
                  print frequency (``0`` to disable).
        """
        super().__init__(device=torch.device(device), **kwargs)
        self.n_samples = n_samples
        self.shrinkage_strength = shrinkage_strength
        self.min_samples_per_stock = min_samples_per_stock

        # Evaluation settings (from nested YAML block or defaults)
        eval_cfg = dict(evaluation) if evaluation else {}
        self.structural_metrics: bool = eval_cfg.get("structural_metrics", False)
        self.structural_max_lag: int = eval_cfg.get("structural_max_lag", 2)
        self.structural_n_eigenvalues: int = eval_cfg.get("structural_n_eigenvalues", 5)
        self.nll_metrics: bool = eval_cfg.get("nll_metrics", False)
        self.log_every_n_batches: int = eval_cfg.get("log_every_n_batches", 10)
        self.plot_bins: int = eval_cfg.get("plot_bins", 60)
        self.plot_dpi: int = eval_cfg.get("plot_dpi", 150)
        self.plot_nll_log_x: bool = bool(eval_cfg.get("plot_nll_log_x", True))
        # When True, save raw plot-data sidecars (.npz) next to every
        # polished PDF so that figures can be regenerated by
        # ``python -m graph_signal_diffusion.cli.replot_baselines`` without
        # re-running evaluation.
        self.dump_plot_data: bool = bool(eval_cfg.get("dump_plot_data", True))

        # Fitted parameters (populated by fit())
        self.global_mean: Optional[float] = None
        self.global_std: Optional[float] = None
        self.per_stock_means: Dict[int, float] = {}
        self.per_stock_stds: Dict[int, float] = {}
        self.n_stocks: int = 0

    # ------------------------------------------------------------------
    # Fitting
    # ------------------------------------------------------------------

    def fit(
        self,
        train_loader: DataLoader,
        val_loader: Optional[DataLoader] = None,
        **kwargs,
    ):
        """Estimate per-stock (μ_s, σ_s) with empirical Bayes shrinkage.

        Steps:
            1. Collect all z-scored log returns from ``batch.y`` per stock.
            2. Compute global statistics (μ_global, σ_global).
            3. Per stock with ≥ ``min_samples_per_stock`` observations,
               compute MLE (μ_s, σ_s) and shrink toward the global:
               ``λ = n_s / (n_s + k)``; ``μ̃_s = λ·μ_s + (1−λ)·μ_global``.
            4. Stocks with too few observations use global parameters.
        """
        print("\nFitting GRW baseline with shrinkage...")

        returns_by_stock: Dict[int, List[torch.Tensor]] = defaultdict(list)
        all_returns: List[torch.Tensor] = []

        for batch in train_loader:
            batch = batch.to("cpu")  # collect on CPU to avoid GPU OOM
            log_returns = batch.y.squeeze(-1)  # [B*N, T]
            B = batch.num_graphs
            N = log_returns.size(0) // B
            log_returns = log_returns.view(B, N, -1)  # [B, N, T]

            for s in range(N):
                stock_ret = log_returns[:, s, :].reshape(-1)  # [B*T]
                returns_by_stock[s].append(stock_ret)
                all_returns.append(stock_ret)

        # Global statistics
        all_returns_t = torch.cat(all_returns)
        self.global_mean = all_returns_t.mean().item()
        self.global_std = all_returns_t.std().item()

        # Sanity-check: in standardised space std should be ≈ 1
        if abs(self.global_std - 1.0) > 0.5:
            warnings.warn(
                f"GRW fit: global std = {self.global_std:.4f} (expected ≈ 1.0 "
                f"for standardised data). Check that the dataset applies "
                f"per-stock z-scoring before training."
            )

        print(f"Global parameters: μ={self.global_mean:.6f}, σ={self.global_std:.6f}")

        # Per-stock parameters with shrinkage
        self.n_stocks = len(returns_by_stock)
        print(f"Computing per-stock parameters for {self.n_stocks} stocks...")

        for s in range(self.n_stocks):
            stock_ret = torch.cat(returns_by_stock[s])
            n_obs = len(stock_ret)

            if n_obs >= self.min_samples_per_stock:
                mu_s = stock_ret.mean().item()
                sigma_s = stock_ret.std().item()
                lam = n_obs / (n_obs + self.shrinkage_strength)
                self.per_stock_means[s] = lam * mu_s + (1 - lam) * self.global_mean
                self.per_stock_stds[s] = lam * sigma_s + (1 - lam) * self.global_std
            else:
                self.per_stock_means[s] = self.global_mean
                self.per_stock_stds[s] = self.global_std

        print(f"Fitted {len(self.per_stock_means)} stocks")
        print(
            f"Mean range: [{min(self.per_stock_means.values()):.6f}, "
            f"{max(self.per_stock_means.values()):.6f}]"
        )
        print(
            f"Std range:  [{min(self.per_stock_stds.values()):.6f}, "
            f"{max(self.per_stock_stds.values()):.6f}]"
        )

    # ------------------------------------------------------------------
    # Vectorised sampling helper
    # ------------------------------------------------------------------

    def _sample_returns(self, B: int, T: int, N: int) -> torch.Tensor:
        """Sample i.i.d. z-scored returns for all stocks (vectorised).

        Returns:
            Tensor of shape ``[B, T, N, 1]`` on ``self.device``.
        """
        # Build per-stock parameter tensors [N]
        mu = torch.tensor(
            [self.per_stock_means.get(s, self.global_mean) for s in range(N)],
            device=self.device,
        )
        sigma = torch.tensor(
            [self.per_stock_stds.get(s, self.global_std) for s in range(N)],
            device=self.device,
        )

        # Sample: [B, T, N] ~ N(0,1), then scale
        z = torch.randn(B, T, N, device=self.device)
        returns = z * sigma.unsqueeze(0).unsqueeze(0) + mu.unsqueeze(0).unsqueeze(0)
        return returns.unsqueeze(-1)  # [B, T, N, 1]

    # ------------------------------------------------------------------
    # Analytical likelihood
    # ------------------------------------------------------------------

    def compute_nll(self, returns: torch.Tensor) -> torch.Tensor:
        """Compute per-trajectory NLL under the fitted GRW model.

        Each trajectory's NLL is the **sum** (not mean) of per-step,
        per-stock negative log-likelihoods.  No averaging over time,
        stocks, or batch is applied.  The resulting vector has one entry
        per graph and is the natural unit for NLL histogram comparisons.

        Concretely, for batch element *b*:

        .. math::

            \\text{NLL}_b = -\\sum_{s=1}^{N}\\sum_{t=1}^{T}
            \\log \\mathcal{N}(r_{b,t,s} \\mid \\tilde{\\mu}_s, \\tilde{\\sigma}_s^2)

        Args:
            returns: Standardised log-returns in shape ``[B, T, N]`` or
                ``[B, T, N, 1]`` — the same space as ``batch.y``
                (z-scored log returns, std ≈ 1).

        Returns:
            1-D tensor of shape ``[B]`` containing the per-trajectory NLL
            summed over all *T* timesteps and *N* stocks.
        """
        import math

        if returns.dim() == 4:
            returns = returns.squeeze(-1)  # [B, T, N]
        B, T, N = returns.shape

        mu = torch.tensor(
            [self.per_stock_means.get(s, self.global_mean) for s in range(N)],
            dtype=returns.dtype,
            device=returns.device,
        )  # [N]
        sigma = torch.tensor(
            [self.per_stock_stds.get(s, self.global_std) for s in range(N)],
            dtype=returns.dtype,
            device=returns.device,
        )  # [N]

        # log p(r | μ, σ) = -½ log(2π) - log σ - (r−μ)² / (2σ²)
        log_probs = (
            -0.5 * math.log(2.0 * math.pi)
            - sigma.log()                                            # [N]
            - 0.5 * ((returns - mu) / sigma) ** 2                   # [B, T, N]
        )  # broadcast: result is [B, T, N]

        # Sum over T and N (no averaging) → [B]
        return -log_probs.sum(dim=(1, 2))

    def compute_cumulative_nll(
        self,
        returns: torch.Tensor,
    ) -> torch.Tensor:
        """NLL of *cumulative* log-returns at each horizon under the GRW model.

        For each prediction horizon :math:`t` the cumulative log-return is
        :math:`R_{b,t,s} = \\sum_{\\tau=1}^{t} r_{b,\\tau,s}` and, under GRW
        (i.i.d. steps), the marginal is
        :math:`R_{b,t,s} \\sim \\mathcal{N}(t\\mu_s, t\\sigma_s^2)`.  The NLL
        summed over stocks is therefore:

        .. math::

            \\ell_{b,t} = -\\sum_{s=1}^{N}
            \\log \\mathcal{N}\\!\\left(R_{b,t,s}
            \\,\\middle|\\, t\\mu_s,\\, t\\sigma_s^2\\right)

        Because the GRW distribution at horizon :math:`t` is wider
        than at :math:`t-1`, :math:`\\ell_{b,t}` is NOT stationary:
        if real returns deviate from i.i.d. Gaussian (e.g. via
        autocorrelation or volatility clustering), the gap between the
        real and GRW-generated NLL distributions grows with :math:`t`.

        Args:
            returns: ``[B, T, N]`` or ``[B, T, N, 1]`` standardised
                log-returns.

        Returns:
            ``[B, T]`` tensor: per-trajectory per-horizon cumulative NLL.
        """
        import math

        if returns.dim() == 4:
            returns = returns.squeeze(-1)  # [B, T, N]
        B, T, N = returns.shape

        cum = returns.cumsum(dim=1)  # [B, T, N]  R_{b,t,s}

        mu = torch.tensor(
            [self.per_stock_means.get(s, self.global_mean) for s in range(N)],
            dtype=returns.dtype,
            device=returns.device,
        )  # [N]
        sigma = torch.tensor(
            [self.per_stock_stds.get(s, self.global_std) for s in range(N)],
            dtype=returns.dtype,
            device=returns.device,
        )  # [N]

        # t-step mean and std: [T] broadcast to [1, T, 1]
        t_vec = torch.arange(1, T + 1, dtype=returns.dtype, device=returns.device)
        mu_t    = mu.unsqueeze(0).unsqueeze(0)    * t_vec.view(1, T, 1)   # [1, T, N]
        sigma_t = sigma.unsqueeze(0).unsqueeze(0) * t_vec.view(1, T, 1).sqrt()  # [1, T, N]

        log_probs = (
            -0.5 * math.log(2.0 * math.pi)
            - sigma_t.log()
            - 0.5 * ((cum - mu_t) / sigma_t) ** 2
        )  # [B, T, N]

        return -log_probs.sum(dim=2)  # [B, T]

    # ------------------------------------------------------------------
    # Structural diagnostics
    # ------------------------------------------------------------------

    @staticmethod
    def compute_autocorr_profile(
        returns: torch.Tensor,
        max_lag: int = 10,
    ) -> torch.Tensor:
        """Lag-0…max_lag autocorrelation (standard ACF) of r², averaged over stocks.

        For each lag ``l`` and stock ``s``:

        .. math::

            \\rho_l^{(s)} = \\gamma_l^{(s)} / \\gamma_0^{(s)}

        where :math:`\\gamma_l` uses a single global mean and
        :math:`\\gamma_0 = \\mathrm{Var}(r^2)`.

        Args:
            returns: ``[B, T, N]`` standardised log-returns.
            max_lag: Maximum lag to compute (inclusive).

        Returns:
            ``[max_lag + 1]`` tensor of autocorrelations at lags 0…max_lag.
        """
        B, T, N = returns.shape
        r2 = returns ** 2
        r2_flat = r2.reshape(-1, N)
        mu = r2_flat.mean(0)                      # [N] global mean
        gamma_0 = ((r2_flat - mu) ** 2).mean(0)   # [N] lag-0 autocovariance

        profile = torch.zeros(max_lag + 1)
        profile[0] = 1.0  # ρ(0) = 1
        for lag in range(1, max_lag + 1):
            r2_t = r2[:, :T - lag, :].reshape(-1, N)
            r2_tl = r2[:, lag:, :].reshape(-1, N)

            gamma_l = ((r2_t - mu) * (r2_tl - mu)).mean(0)  # [N]
            rho_l = gamma_l / (gamma_0 + 1e-8)               # [N]
            profile[lag] = rho_l.mean()

        return profile

    @staticmethod
    def compute_autocorr_profile_per_stock(
        returns: torch.Tensor,
        max_lag: int = 10,
    ) -> torch.Tensor:
        """Per-stock lag-0…max_lag autocorrelation (standard ACF) of r².

        Identical to :meth:`compute_autocorr_profile` but retains the
        per-stock dimension instead of averaging over stocks.

        Args:
            returns: ``[B, T, N]`` standardised log-returns.
            max_lag: Maximum lag to compute (inclusive).

        Returns:
            ``[max_lag + 1, N]`` tensor — row *l* holds the ACF at
            lag *l* for every individual stock.  Row 0 is identically 1.
        """
        B, T, N = returns.shape
        r2 = returns ** 2
        r2_flat = r2.reshape(-1, N)
        mu = r2_flat.mean(0)                      # [N] global mean
        gamma_0 = ((r2_flat - mu) ** 2).mean(0)   # [N] lag-0 autocovariance

        profile = torch.zeros(max_lag + 1, N)
        profile[0] = 1.0  # ρ(0) = 1 for every stock
        for lag in range(1, max_lag + 1):
            r2_t  = r2[:, :T - lag, :].reshape(-1, N)
            r2_tl = r2[:, lag:, :].reshape(-1, N)

            gamma_l = ((r2_t - mu) * (r2_tl - mu)).mean(0)  # [N]
            profile[lag] = gamma_l / (gamma_0 + 1e-8)

        return profile  # [max_lag + 1, N]

    @staticmethod
    def compute_top_eigenvalues(
        returns: torch.Tensor, k: int = 5
    ) -> torch.Tensor:
        """Top-k eigenvalues of the empirical return correlation matrix.

        Observations are pooled over *B* batches and *T* timesteps, giving
        an ``[B*T, N]`` design matrix.  Under i.i.d. independent stocks
        (GRW) all eigenvalues are ≈ 1; under a factor model the first
        eigenvalue is ≫ 1.

        Args:
            returns: ``[B, T, N]`` standardised log-returns.
            k: Number of top eigenvalues to return.

        Returns:
            Eigenvalues in descending order, shape ``[k]``.
        """
        B, T, N = returns.shape
        r = returns.reshape(-1, N).float()

        r = r - r.mean(0)
        r = r / (r.std(0) + 1e-8)

        C = (r.T @ r) / r.shape[0]
        vals = torch.linalg.eigvalsh(C)
        return vals.flip(0)[:k]

    compute_structural_metrics = staticmethod(sm.compute_structural_metrics)

    # ------------------------------------------------------------------
    # Visualisation helpers
    # ------------------------------------------------------------------

    @staticmethod
    def _plot_nll_histograms(
        nll_real: Any,
        nll_gen: Any,
        save_path: str,
        bins: int = 60,
        dpi: int = 150,
        log_x: bool = True,
    ) -> None:
        """Save a two-panel NLL histogram + empirical-CDF figure.

        Left panel: overlaid density histograms of per-trajectory NLL for
        real and GRW-generated returns.
        Right panel: empirical CDFs with |ΔCDF| area shaded (W₁ integrand).

        Args:
            nll_real: 1-D numpy array of NLL values for real returns.
            nll_gen:  1-D numpy array of NLL values for generated returns.
            save_path: File path to save the PNG.
            bins: Number of histogram bins.
            dpi: Figure DPI.
        """
        import os
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        import numpy as np
        from scipy.stats import wasserstein_distance as _w1

        w1 = float(_w1(nll_real, nll_gen))

        # Build empirical CDFs
        all_vals = np.concatenate([nll_real, nll_gen])
        x_min, x_max = float(all_vals.min()), float(all_vals.max())
        if log_x and x_min > 0:
            x_grid = np.logspace(np.log10(x_min), np.log10(x_max), 2000)
            hist_bins = np.logspace(np.log10(x_min), np.log10(x_max), bins + 1)
        else:
            x_grid = np.linspace(x_min, x_max, 2000)
            hist_bins = bins

        cdf_real = _ecdf(nll_real, x_grid)
        cdf_gen = _ecdf(nll_gen, x_grid)

        fig, (ax_hist, ax_cdf) = plt.subplots(
            1, 2, figsize=(14, 5),
            gridspec_kw={"width_ratios": [1.2, 1]},
        )

        # Left — density histograms
        ax_hist.hist(
            nll_real, bins=hist_bins, density=True, alpha=0.55, color="steelblue",
            label=(
                r"$\mathrm{NLL}_{\mathrm{GRW}}(r^{\mathrm{real}})$  "
                f"  \u03bc={nll_real.mean():.1f},  \u03c3={nll_real.std():.1f}"
            ),
        )
        ax_hist.hist(
            nll_gen, bins=hist_bins, density=True, alpha=0.50, color="tab:orange",
            label=(
                r"$\mathrm{NLL}_{\mathrm{GRW}}(r^{\mathrm{gen}})$  "
                f"  \u03bc={nll_gen.mean():.1f},  \u03c3={nll_gen.std():.1f}"
            ),
        )
        if log_x and x_min > 0:
            ax_hist.set_xscale("log")
        ax_hist.set_xlabel(
            r"Per-trajectory NLL  $= \sum_{s,t} -\log\,\mathcal{N}"
            r"(r_{s,t}\mid\tilde{\mu}_s,\tilde{\sigma}_s^2)$",
            fontsize=11,
        )
        ax_hist.set_ylabel("Density", fontsize=11)
        ax_hist.set_title("NLL Histograms  (real vs GRW-generated)", fontsize=12)
        ax_hist.legend(fontsize=9)

        # Right — empirical CDFs
        ax_cdf.plot(x_grid, cdf_real, color="steelblue", linewidth=1.8,
                    label=r"$F_{\mathrm{real}}$")
        ax_cdf.plot(x_grid, cdf_gen, color="tab:orange", linewidth=1.8,
                    label=r"$F_{\mathrm{gen}}$")
        ax_cdf.fill_between(
            x_grid, cdf_real, cdf_gen, alpha=0.25, color="mediumpurple",
            label=fr"$|F_{{\rm real}} - F_{{\rm gen}}|$  (area = W$_1$ = {w1:.2f})",
        )
        if log_x and x_min > 0:
            ax_cdf.set_xscale("log")
        ax_cdf.set_xlabel(r"Per-trajectory NLL  $\ell$", fontsize=11)
        ax_cdf.set_ylabel("Empirical CDF", fontsize=11)
        ax_cdf.set_title(
            f"Empirical CDFs \u2014 $W_1 = {w1:.2f}$ nats", fontsize=12,
        )
        ax_cdf.legend(fontsize=9)
        ax_cdf.set_ylim(0, 1)

        # fig.tight_layout()
        os.makedirs(os.path.dirname(save_path) or ".", exist_ok=True)
        fig.savefig(save_path, dpi=dpi)
        plt.close(fig)
        print(f"  [GRW] NLL histogram saved to: {save_path}")

    @staticmethod
    def _plot_cumulative_nll_histograms(
        nll_real_bt: Any,
        nll_gen_bt: Any,
        save_path: str,
        bins: int = 60,
        dpi: int = 150,
    ) -> None:
        """Plot cumulative-return NLL histograms + CDFs for each horizon.

        Produces a 2-row grid with *T* columns (one per prediction horizon):

        * **Top row** — overlaid density histograms of
          :math:`\\ell_{b,t}^{\\text{real}}` and
          :math:`\\ell_{b,t}^{\\text{gen}}` under the :math:`t`-step GRW
          model, including their means.
        * **Bottom row** — empirical CDFs of both distributions with the
          :math:`|\\Delta F|` area shaded and the Wasserstein-1 distance
          annotated.

        Args:
            nll_real_bt: ``[B, T]`` numpy array — cumulative NLL (real).
            nll_gen_bt:  ``[B, T]`` numpy array — cumulative NLL (generated).
            save_path:   Destination file path.
            bins:        Histogram bins per panel.
            dpi:         Figure DPI.
        """
        import os
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        import numpy as np
        from scipy.stats import wasserstein_distance as _w1

        B, T = nll_real_bt.shape

        fig, axes = plt.subplots(
            2, T,
            figsize=(7 * T, 10),
            gridspec_kw={"hspace": 0.40, "wspace": 0.28},
        )
        # Ensure axes is always 2-D
        if T == 1:
            axes = axes.reshape(2, 1)

        w1_values = []
        for t in range(T):
            real_t = nll_real_bt[:, t]
            gen_t  = nll_gen_bt[:, t]
            w1     = float(_w1(real_t, gen_t))
            w1_values.append(w1)

            # ---- top: histograms ----------------------------------------
            ax_h = axes[0, t]
            all_t = np.concatenate([real_t, gen_t])
            lo, hi = np.percentile(all_t, 0.5), np.percentile(all_t, 99.5)
            bin_edges = np.linspace(lo, hi, bins + 1)

            ax_h.hist(real_t, bins=bin_edges, density=True,
                      alpha=0.55, color="steelblue",
                      label=(
                          r"real  $\mu$=" + f"{real_t.mean():.1f}"
                          + r",  $\sigma$=" + f"{real_t.std():.1f}"
                      ))
            ax_h.hist(gen_t, bins=bin_edges, density=True,
                      alpha=0.50, color="tab:orange",
                      label=(
                          r"gen  $\mu$=" + f"{gen_t.mean():.1f}"
                          + r",  $\sigma$=" + f"{gen_t.std():.1f}"
                      ))
            ax_h.set_title(f"$t = {t+1}$", fontsize=14)
            ax_h.set_xlabel(
                r"Cumulative NLL  $\ell_{b," + str(t+1) + r"}$",
                fontsize=11,
            )
            if t == 0:
                ax_h.set_ylabel("Density", fontsize=11)
            ax_h.legend(fontsize=9)

            # ---- bottom: CDFs -------------------------------------------
