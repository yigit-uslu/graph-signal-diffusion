    # ------------------------------------------------------------------
    # Prediction (single-sample, for UnifiedEvaluator's generic path)
    # ------------------------------------------------------------------

    def predict(self, data) -> torch.Tensor:
        """Return *point* predictions (ensemble mean) as ``[B, T, N, 1]``.

        This is used by ``UnifiedEvaluator.evaluate_baseline`` for baselines
        that don't declare ``has_ensemble_evaluate``.  For GRW the ensemble
        mean is just ``(μ_s)`` repeated, since each draw is i.i.d.
        """
        B = data.num_graphs
        N = data.y.size(0) // B
        T = data.y.size(1)

        # Analytical mean — no need to actually sample
        mu = torch.tensor(
            [self.per_stock_means.get(s, self.global_mean) for s in range(N)],
            device=self.device,
        )
        # Broadcast to [B, T, N, 1]
        return mu.view(1, 1, N, 1).expand(B, T, -1, -1).clone()

    # ------------------------------------------------------------------
    # Ensemble prediction (multi-sample)
    # ------------------------------------------------------------------

    def predict_ensemble(self, data) -> torch.Tensor:
        """Generate ``n_samples`` i.i.d. return paths per input.

        Returns:
            ``[B * n_samples, T, N, 1]`` with samples for the same input
            contiguous (positions ``[b*n .. (b+1)*n - 1]``).
        """
        B = data.num_graphs
        N = data.y.size(0) // B
        T = data.y.size(1)

        samples = []
        for _ in range(self.n_samples):
            samples.append(self._sample_returns(B, T, N))

        # Stack → [B, n, T, N, 1], then interleave to [B*n, T, N, 1]
        stacked = torch.stack(samples, dim=1)  # [B, n, T, N, 1]
        return stacked.reshape(B * self.n_samples, T, N, 1)

    # ------------------------------------------------------------------
    # Evaluation (full V2-compatible pipeline)
    # ------------------------------------------------------------------

    def evaluate(
        self,
        loader: DataLoader,
        task,
        max_batches: Optional[int] = None,
        viz_save_dir: Optional[str] = None,
        eval_split_name: str = "eval",
    ) -> Dict[str, float]:
        """Evaluate with the TaskV2 probabilistic pipeline (per-batch).

        Follows the same pattern as ``DiffusionTrainer.evaluate_v2``:
        evaluate each batch independently via ``task.evaluate_samples()``,
        accumulate the scalar metrics, and average at the end.  This avoids
        concatenating all predictions/targets into a single tensor which
        would cause GPU OOM on large datasets.

        For each batch:
        1. ``task.prepare_data(data)`` → targets ``[B, T, N, F]`` + metadata.
        2. ``predict_ensemble(data)`` → ``[B*n, T, N, F]``.
        3. Replicate targets & metadata tensors ``n`` times to match.
        4. Call ``task.evaluate_samples()`` **per batch** to get metrics.
        5. Accumulate metrics across batches and average.

        When ``self.structural_metrics`` is enabled, per-batch real/generated
        return tensors are accumulated along with ``window_start_indices``
        extracted from ``metadata['timestamp']``.  The phased estimator then
        groups windows by ``start_index % T`` rather than positional order,
        making the spectral diagnostics correct on any DataLoader ordering.

        Args:
            loader: DataLoader to iterate over.
            task: Task instance with ``prepare_data()`` and ``evaluate_samples()``.
            max_batches: Maximum number of batches to process.  ``None`` →
                process all batches.  Use ``max_batches=1`` for quick
                single-batch validation.
            viz_save_dir: Directory to save per-batch visualisations.  Passed
                through to ``task.evaluate_samples()``.
        """
        total_batches = len(loader) if max_batches is None else min(max_batches, len(loader))
        batch_limit_str = f" (first {total_batches})" if max_batches is not None else ""

        # Per-batch metric accumulator (same as DiffusionTrainer)
        task_metrics: Dict[str, float] = {}
        count = 0

        # Optional accumulators for structural / NLL diagnostics
        all_real_returns: List[torch.Tensor] = []
        all_gen_returns: List[torch.Tensor] = []
        # Pooled full ensemble for stylized-fact computation:
        # [B*n, T, N] per batch — every generated sample for every window.
        all_gen_returns_full: List[torch.Tensor] = []
        all_start_indices: List[torch.Tensor] = []
        all_nll_real: List[torch.Tensor] = []
        all_nll_gen: List[torch.Tensor] = []
        all_cum_nll_real: List[torch.Tensor] = []
        all_cum_nll_gen: List[torch.Tensor] = []

        print(f"\nGenerating GRW ensemble predictions on [{eval_split_name}]{batch_limit_str}...")
        for i, data in tqdm(enumerate(loader), desc=f"GRW [{eval_split_name}]", total=total_batches):
            data = data.to(self.device)

            # Ground truth via task (returns [B, T, N, F] in standardised space)
            data_dict = task.prepare_data(data)
            targets = data_dict["samples"]      # [B, T, N, F]
            metadata = data_dict["metadata"]

            B = targets.size(0)

            # ----------------------------------------------------------
            # Detect double-replication: if the loader's dataset is a
            # ReplicatedDataset the data is already duplicated n times.
            # GRW generates its *own* n samples via predict_ensemble(),
            # so feeding it pre-replicated data is a config error.
            #
            # NOTE: metadata['n_samples_per_input'] comes from the *task*
            # config (not the dataset), so it may be >1 even when the
            # dataset is un-replicated.  We only check on the first batch.
            # ----------------------------------------------------------
            if i == 0:
                from graph_signal_diffusion.datasets.replicated_dataset import ReplicatedDataset
                raw_dataset = getattr(loader, "dataset", None)
                if isinstance(raw_dataset, ReplicatedDataset):
                    raise RuntimeError(
                        "GRW detected a ReplicatedDataset in the loader.  "
                        "GRW handles its own multi-sample generation, so the "
                        "dataset must use n_samples_per_input=1 to avoid "
                        "double replication.  Set dataset.n_samples_per_input=1 "
                        "in your config or CLI override."
                    )

            # Ensemble predictions [B*n, T, N, F]
            predictions = self.predict_ensemble(data)

            # Replicate targets to [B*n, T, N, F] (same as ReplicatedDataset)
            targets_rep = targets.repeat_interleave(self.n_samples, dim=0)

            # Replicate tensor-valued metadata along dim 0
            meta_rep = self._replicate_metadata(metadata, self.n_samples)
            meta_rep["n_samples_per_input"] = self.n_samples
            meta_rep["batch_size"] = B * self.n_samples

            # Evaluate this batch immediately (no accumulation of tensors)
            batch_metrics = task.evaluate_samples(
                predictions, targets_rep, meta_rep, viz_save_dir=viz_save_dir
            )

            # ----------------------------------------------------------
            # Collect returns for structural / NLL diagnostics
            # ----------------------------------------------------------
            if self.structural_metrics or self.nll_metrics:
                # [B, T, N] — squeeze feature dim
                real_ret = targets.squeeze(-1).detach().cpu()
                # First sample per input only (1-to-1 with ground truth).
                # predictions is [B*n, T, N, 1] reshaped from [B, n, T, N, 1],
                # so element k = (batch k//n, sample k%n).  Stride by n_samples
                # to select sample-0 for every batch item.
                gen_ret = predictions[::self.n_samples].squeeze(-1).detach().cpu()

            if self.structural_metrics:
                all_real_returns.append(real_ret)
                all_gen_returns.append(gen_ret)
                # Full pooled ensemble for stylized-fact recompute.
                # predictions: [B*n, T, N, 1] → [B*n, T, N]
                all_gen_returns_full.append(
                    predictions.squeeze(-1).detach().cpu()
                )
                # Extract per-window start index from timestamp metadata
                ts = metadata.get("timestamp", None)
                if ts is not None:
                    N_nodes = real_ret.shape[2]  # number of stocks
                    # timestamp is [B*N]; take every N-th element
                    idx = ts[::N_nodes].detach().cpu().long()
                    all_start_indices.append(idx)

            if self.nll_metrics:
                all_nll_real.append(self.compute_nll(real_ret))
                all_nll_gen.append(self.compute_nll(gen_ret))
                all_cum_nll_real.append(self.compute_cumulative_nll(real_ret))
                all_cum_nll_gen.append(self.compute_cumulative_nll(gen_ret))

            # Accumulate scalar metrics (same pattern as DiffusionTrainer)
            for k, v in batch_metrics.items():
                if k not in task_metrics:
                    task_metrics[k] = 0.0
                task_metrics[k] += v
            count += 1

            if self.log_every_n_batches and (i + 1) % self.log_every_n_batches == 0:
                print(f"  Processed {i + 1}/{total_batches} batches")

            # Stop if we've reached the batch limit
            if max_batches is not None and (i + 1) >= max_batches:
                break

        # Average task metrics across batches
        metrics: Dict[str, float] = {}
        for k in task_metrics:
            metrics[k] = task_metrics[k] / max(count, 1)

        # ----------------------------------------------------------
        # Structural metrics (cross-stock & temporal diagnostics)
        # ----------------------------------------------------------
        if self.structural_metrics and all_real_returns:
            cat_real = torch.cat(all_real_returns, dim=0)
            cat_gen = torch.cat(all_gen_returns, dim=0)
            cat_indices = (
                torch.cat(all_start_indices, dim=0)
                if all_start_indices else None
            )
            T_steps = cat_real.shape[1]
            struct = self.compute_structural_metrics(
                cat_real, cat_gen,
                max_lag=self.structural_max_lag,
                n_eigenvalues=self.structural_n_eigenvalues,
                window_stride=T_steps,
                window_start_indices=cat_indices,
            )
            metrics.update(struct)

            # ----------------------------------------------------------
            # Recompute non-linear stylized facts (kurtosis / vol-clustering /
            # momentum / top-eigval) on the *full* concatenated tensors.
            # task.evaluate_samples() computes these per-batch and the loop
            # above averages the per-batch values, which is biased for
            # 4th-moment / ratio-style statistics.  Computing them once over
            # all accumulated returns gives the unbiased dataset-level value
            # and makes cross-baseline comparison meaningful.
            #
            # cat_real has one trajectory per window; cat_gen_full pools all
            # n_samples generated trajectories for each window for a much
            # lower-variance estimate of the model's distribution.
            try:
                from graph_signal_diffusion.tasks.stock_price_forecasting.evaluator import (
                    StockPriceForecastingTaskV2,
                )
                cat_gen_full = torch.cat(all_gen_returns_full, dim=0)
                metrics.update(
                    StockPriceForecastingTaskV2.compute_stylized_facts_from_tensors(
                        cat_real, cat_gen_full,
                    )
                )
            except Exception:
                import traceback
                print(
                    "[GRW] Failed to recompute stylized facts on full tensors; "
                    "keeping per-batch averages.\n" + traceback.format_exc()
                )

            # Expose tensors for cross-baseline comparative plots
            self.last_structural_tensors = {
                "real": cat_real,
                "gen": cat_gen,
                "window_start_indices": cat_indices,
                "window_stride": T_steps,
            }

            if viz_save_dir is not None:
                import os
                self._plot_structural_metrics(
                    cat_real, cat_gen,
                    save_path=os.path.join(viz_save_dir, "structural_metrics_grw.pdf"),
                    max_lag=self.structural_max_lag,
                    n_eigenvalues=self.structural_n_eigenvalues,
                    dpi=self.plot_dpi,
                    window_stride=T_steps,
                    window_start_indices=cat_indices,
                )
                self._plot_autocorr_per_stock(
                    cat_real, cat_gen,
                    save_path=os.path.join(viz_save_dir, "autocorr_per_stock_grw.pdf"),
                    max_lag=self.structural_max_lag,
                    dpi=self.plot_dpi,
                    window_stride=T_steps,
                    window_start_indices=cat_indices,
                )
                sm.plot_autocorr_violin(
                    cat_real, cat_gen,
                    save_path=os.path.join(viz_save_dir, "autocorr_violin_grw.pdf"),
                    max_lag=self.structural_max_lag,
                    dpi=self.plot_dpi,
                    model_name="GRW",
                    window_stride=T_steps,
                    window_start_indices=cat_indices,
                )
                sm.plot_autocorr_heatmap(
                    cat_gen,
                    save_path=os.path.join(viz_save_dir, "autocorr_heatmap_grw.pdf"),
                    max_lag=self.structural_max_lag,
                    dpi=self.plot_dpi,
                    model_name="GRW",
                    window_stride=T_steps,
                    window_start_indices=cat_indices,
                    real_returns=cat_real,
                )
                # Cumulative-return std vs horizon
                import numpy as np
                N_stocks = cat_real.shape[2]
                T_steps  = cat_real.shape[1]
                sigma_bar = float(np.mean(
                    [self.per_stock_stds.get(s, self.global_std)
                     for s in range(N_stocks)]
                ))
                theoretical = sigma_bar * np.sqrt(np.arange(1, T_steps + 1))
                _cum_std_real = self.compute_cumulative_return_std(cat_real).numpy()
                _cum_std_gen = self.compute_cumulative_return_std(cat_gen).numpy()
                _cum_std_real_tn = self.compute_cumulative_return_std(
                    cat_real, per_stock=True,
                ).numpy()
                _cum_std_gen_tn = self.compute_cumulative_return_std(
                    cat_gen, per_stock=True,
                ).numpy()
                self._plot_cumulative_return_std(
                    _cum_std_real, _cum_std_gen,
                    save_path=os.path.join(viz_save_dir, "cumulative_return_std_grw.pdf"),
                    theoretical=theoretical,
                    std_real_tn=_cum_std_real_tn,
                    std_gen_tn=_cum_std_gen_tn,
                    dpi=self.plot_dpi,
                )

                # Dump consolidated plot-data sidecar for replot_baselines.
                if self.dump_plot_data:
                    try:
                        from graph_signal_diffusion.evaluation.plot_data_io import (
                            dump_per_baseline_structural,
                        )
                        dump_per_baseline_structural(
                            os.path.join(viz_save_dir, "structural_data.npz"),
                            cat_real=cat_real,
                            cat_gen=cat_gen,
                            model_name="GRW",
                            max_lag=self.structural_max_lag,
                            n_eigenvalues=self.structural_n_eigenvalues,
                            window_stride=T_steps,
                            window_start_indices=cat_indices,
                            cum_std_real=_cum_std_real,
                            cum_std_gen=_cum_std_gen,
                            cum_std_real_tn=_cum_std_real_tn,
                            cum_std_gen_tn=_cum_std_gen_tn,
                            theoretical=theoretical,
                            dpi=self.plot_dpi,
                        )
                    except Exception:
                        import traceback
                        print(
                            "[GRW] Failed to dump structural plot data sidecar:\n"
                            + traceback.format_exc()
                        )

        # ----------------------------------------------------------
        # NLL metrics (per-trajectory NLL histograms + W1 distance)
        # ----------------------------------------------------------
        if self.nll_metrics and all_nll_real:
            nll_real = torch.cat(all_nll_real)
            nll_gen = torch.cat(all_nll_gen)
            metrics["nll_mean_real"] = nll_real.mean().item()
            metrics["nll_mean_gen"] = nll_gen.mean().item()
            metrics["nll_std_real"] = nll_real.std().item()
            metrics["nll_std_gen"] = nll_gen.std().item()
            nll_real_np = nll_real.numpy()
            nll_gen_np = nll_gen.numpy()
            metrics["nll_w1"] = float(
                wasserstein_distance(nll_real_np, nll_gen_np)
            )

            # Cumulative-return NLL tensors — always computed so that
            # cross-baseline consumers can read last_nll_tensors without
            # requiring a viz directory.
            cum_nll_real_bt = torch.cat(all_cum_nll_real).numpy()  # [B_total, T]
            cum_nll_gen_bt  = torch.cat(all_cum_nll_gen).numpy()

            # Expose for cross-baseline comparative NLL plots
            self.last_nll_tensors = {
                "nll_real": nll_real_np,
                "nll_gen": nll_gen_np,
                "cum_nll_real": cum_nll_real_bt,
                "cum_nll_gen": cum_nll_gen_bt,
            }

            if viz_save_dir is not None:
                import os
                self._plot_nll_histograms(
                    nll_real_np, nll_gen_np,
                    save_path=os.path.join(viz_save_dir, "nll_histogram_grw.pdf"),
                    bins=self.plot_bins,
                    dpi=self.plot_dpi,
                    log_x=self.plot_nll_log_x,
                )
                w1_per_t = self._plot_cumulative_nll_histograms(
                    cum_nll_real_bt, cum_nll_gen_bt,
                    save_path=os.path.join(viz_save_dir, "cumulative_nll_histogram_grw.pdf"),
                    bins=self.plot_bins,
                    dpi=self.plot_dpi,
                )

                if self.dump_plot_data:
                    try:
                        from graph_signal_diffusion.evaluation.plot_data_io import (
                            dump_per_baseline_nll,
                        )
                        dump_per_baseline_nll(
                            os.path.join(viz_save_dir, "nll_data.npz"),
                            nll_real=nll_real_np,
                            nll_gen=nll_gen_np,
                            cum_nll_real_bt=cum_nll_real_bt,
                            cum_nll_gen_bt=cum_nll_gen_bt,
                            bins=self.plot_bins,
                            dpi=self.plot_dpi,
                            log_x=self.plot_nll_log_x,
                            scoring_model_name="GRW",
                        )
                    except Exception:
                        import traceback
                        print(
                            "[GRW] Failed to dump NLL plot data sidecar:\n"
                            + traceback.format_exc()
                        )
                if w1_per_t is not None:
                    for ti, w in enumerate(w1_per_t):
                        metrics[f"cum_nll_w1_t{ti+1}"] = w

        print(
            f"\nGRW [{eval_split_name}]: evaluated {count} batches (averaged metrics over {count} batches)"
        )

        return metrics

