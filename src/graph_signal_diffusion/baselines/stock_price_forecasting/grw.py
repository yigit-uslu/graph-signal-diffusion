    @staticmethod
    def save_comparison_metrics_markdown(
        csv_path: str,
        output_path: Optional[str] = None,
        metrics: Optional[List[str]] = None,
        splits: Optional[List[str]] = None,
        decimals: int = 4,
        format: str = "grouped",
    ):
        """Save formatted metrics table to a markdown file.
        
        This is a convenience method that wraps the evaluation utility function
        for saving comparison results as markdown.
        
        Args:
            csv_path: Path to baseline_comparison.csv file.
            output_path: Path to save the markdown file. If None, saves to the same
                        directory as csv_path with name 'metrics_summary.md'.
            metrics: List of metric names to extract. 
                     Defaults to ['rmse', 'crps_mean', 'crps_std', 'mae', 'mse'].
            splits: List of data splits. Defaults to ['train-val', 'val', 'test'].
            decimals: Number of decimal places to display.
            format: Display format - "grouped" (by split) or "flat" (single table).
        
        Example:
            >>> GeometricRandomWalk.save_comparison_metrics_markdown(
            ...     'outputs/stock_price_forecasting_v2-sp500_cleaned/comparison/2026-02-16/14-15-25/baseline_comparison.csv'
            ... )
        """
        from graph_signal_diffusion.evaluation import save_metrics_table_markdown
        from pathlib import Path
        
        if output_path is None:
            csv_dir = Path(csv_path).parent
            output_path = str(csv_dir / "metrics_summary.md")
        
        return save_metrics_table_markdown(
            csv_path, output_path,
            metrics=metrics, splits=splits,
            decimals=decimals, format=format
        )